import assert from 'node:assert/strict';
import fs from 'node:fs';
const performance=fs.readFileSync(new URL('../website/performance.js',import.meta.url),'utf8');
const app=fs.readFileSync(new URL('../website/app.js',import.meta.url),'utf8');
const declaration=performance.match(/function paginateList\(list,page,pageSize\)\{[^\n]*\}/)?.[0];
assert.ok(declaration,'Shared pagination helper must exist');
const paginate=Function(declaration+'\nreturn paginateList')();
const ships=Array.from({length:600},(_,index)=>index);
const mobileFirst=paginate(ships,1,24);
assert.equal(mobileFirst.items.length,24);
assert.equal(mobileFirst.items[0],0);
assert.equal(mobileFirst.items.at(-1),23);
assert.equal(mobileFirst.totalPages,25);
const desktopLast=paginate(ships,99,48);
assert.equal(desktopLast.current,13);
assert.equal(desktopLast.totalPages,13);
assert.equal(desktopLast.items.length,24);
assert.equal(desktopLast.items[0],576);
assert.equal(paginate([],1,24).totalPages,1);
assert.equal(paginate(ships,0,48).current,1);
assert.doesNotMatch(app,/querySelectorAll\('\\.ship-card'\\)/,'Ship cards should not receive per-card click listeners');
assert.match(app,/document\.addEventListener\('click',event=>/,'Ship card clicks should be delegated');
assert.match(app,/document\.addEventListener\('keydown',event=>/,'Keyboard activation should also be delegated');
console.log('PASS: ship pagination boundaries, responsive page sizes and delegated interactions');
